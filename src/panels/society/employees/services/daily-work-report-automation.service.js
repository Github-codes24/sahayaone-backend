import { DailyWorkReport } from "../../../../models/daily-work-report.model.js";
import { SocietyEmployee } from "../../../../models/society-employee.model.js";
import { BranchManager } from "../../../../models/branch-manager.model.js";
import { logger } from "../../../../utils/logger.util.js";

export class DailyWorkReportAutomationService {
  /**
   * Automatically record a daily work report entry triggered by system events (Receipts, Cash Collections, Loans).
   */
  async recordWorkReport({
    bankId,
    branchId = null,
    employeeId,
    date = new Date(),
    product,
    amount,
    sourceModule = "MANUAL",
    referenceId = null,
    remarks = "",
    createdBy = null,
  }) {
    if (!bankId || !employeeId || !product || amount === undefined || amount === null) {
      logger.warn(
        `AUTO WORK REPORT BYPASSED: Missing required parameters (bankId: ${bankId}, employeeId: ${employeeId}, product: ${product}, amount: ${amount})`
      );
      return null;
    }

    const numAmount = Number(amount);
    if (isNaN(numAmount) || numAmount <= 0) {
      logger.info(
        `AUTO WORK REPORT BYPASSED: Zero or negative amount (${amount}) for product ${product}`
      );
      return null;
    }

    // Deduplication check: if referenceId & sourceModule are provided, prevent duplicate logging
    if (referenceId && sourceModule !== "MANUAL") {
      const existing = await DailyWorkReport.findOne({
        referenceId,
        sourceModule,
        isDeleted: { $ne: true },
      }).lean();

      if (existing) {
        logger.info(
          `AUTO WORK REPORT SKIPPED: Already recorded for referenceId ${referenceId} in module ${sourceModule}`
        );
        return existing;
      }
    }

    // Resolve employee profile & branchId whether employeeId is User._id or SocietyEmployee._id/BranchManager._id
    let resolvedEmployeeId = employeeId;
    let resolvedBranchId = branchId;

    let empDoc = await SocietyEmployee.findOne({
      $or: [{ _id: employeeId }, { userId: employeeId }],
      isDeleted: { $ne: true }
    }).select("_id branchId").lean();

    if (!empDoc) {
      empDoc = await BranchManager.findOne({
        $or: [{ _id: employeeId }, { userId: employeeId }],
        isDeleted: { $ne: true }
      }).select("_id branchId").lean();
    }

    if (empDoc) {
      resolvedEmployeeId = empDoc._id;
      if (!resolvedBranchId && empDoc.branchId) {
        resolvedBranchId = empDoc.branchId;
      }
    }

    if (!resolvedBranchId) {
      logger.warn(
        `AUTO WORK REPORT WARNING: Could not resolve branchId for employee ${employeeId}`
      );
    }

    const reportDate = date ? new Date(date) : new Date();

    const report = new DailyWorkReport({
      employeeId: resolvedEmployeeId,
      bankId,
      branchId: resolvedBranchId,
      date: reportDate,
      product: String(product).trim(),
      amount: numAmount,
      remarks: remarks || `Automated entry from ${sourceModule}`,
      isAutoGenerated: sourceModule !== "MANUAL",
      sourceModule,
      referenceId,
      createdBy,
    });

    await report.save();

    logger.info(
      `AUTO WORK REPORT CREATED: Employee ${employeeId} | Product: ${product} | Amount: ₹${numAmount} | Module: ${sourceModule} | Ref: ${referenceId || "N/A"}`
    );

    return report;
  }
}

export const dailyWorkReportAutomationService = new DailyWorkReportAutomationService();
