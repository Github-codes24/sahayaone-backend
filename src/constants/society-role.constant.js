export function normalizeRoleCode(code) {
  if (!code) return '';
  const c = String(code).trim().toUpperCase();
  if (c === 'BRANCH_MANAGER') return 'MANAGER';
  if (c === 'HR_MANAGER' || c === 'HR_EXECUTIVE') return 'HR';
  if (c === 'ACCOUNTANT_EXECUTIVE') return 'ACCOUNTANT';
  if (c === 'RECEIPT_EXECUTIVE' || c === 'RECEIPT_MANAGEMENT' || c === 'BANK_RECEIPT_MANAGER') return 'RECEIPT_MANAGEMENT_EXECUTIVE';
  if (c === 'RECEIPT_EXECUTIVE' || c === 'RECEIPT_MANAGEMENT') return 'RECEIPT_MANAGEMENT_EXECUTIVE';
  if (c === 'BANK_RECEIPT_MANAGER' || c === 'RECEIPT_HEAD' || c === 'RECEIPT_ADMIN') return 'RECEIPT_MANAGER';
  if (c === 'QUALITY_CHECK' || c === 'QUALITY_CHECKER' || c === 'QC') return 'QC';
  return c;
}

export function isBranchManagerRole(roleInput) {
  if (!roleInput) return false;

  if (typeof roleInput === 'string') {
    const codeUpper = roleInput.trim().toUpperCase();
    const norm = normalizeRoleCode(codeUpper);
    return codeUpper === 'BRANCH_MANAGER' || codeUpper === 'MANAGER' || norm === 'MANAGER';
  }

  const roleCodeUpper = (roleInput.code || '').trim().toUpperCase();
  const roleNameUpper = (roleInput.name || '').trim().toUpperCase();
  const normCode = normalizeRoleCode(roleCodeUpper);

  if (roleCodeUpper === 'BRANCH_MANAGER' || roleCodeUpper === 'MANAGER' || normCode === 'MANAGER') {
    return true;
  }

  if (roleNameUpper === 'BRANCH MANAGER' || roleNameUpper.includes('BRANCH MANAGER')) {
    return true;
  }

  return false;
}

export function isQualityCheckRole(roleInput) {
  if (!roleInput) return false;

  if (typeof roleInput === 'string') {
    const codeUpper = roleInput.trim().toUpperCase();
    const norm = normalizeRoleCode(codeUpper);
    return codeUpper === 'QC' || codeUpper === 'QUALITY_CHECK' || codeUpper === 'QUALITY_CHECKER' || norm === 'QC';
  }

  const roleCodeUpper = (roleInput.code || '').trim().toUpperCase();
  const roleNameUpper = (roleInput.name || '').trim().toUpperCase();
  const normCode = normalizeRoleCode(roleCodeUpper);

  if (roleCodeUpper === 'QC' || roleCodeUpper === 'QUALITY_CHECK' || roleCodeUpper === 'QUALITY_CHECKER' || normCode === 'QC') {
    return true;
  }

  if (roleNameUpper === 'QUALITY CHECK' || roleNameUpper.includes('QUALITY CHECK') || roleNameUpper.includes('QC')) {
    return true;
  }

  return false;
}

