import mongoose from 'mongoose';
import softDeletePlugin from '../database/plugins/soft-delete.plugin.js';

const dailyWorkReportSchema = new mongoose.Schema(
  {
    employeeId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'SocietyEmployee',
      required: true,
      index: true
    },
    bankId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Bank',
      required: true,
      index: true
    },
    branchId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Branch',
      required: true,
      index: true
    },
    date: {
      type: Date,
      required: true,
      index: true
    },
    product: {
      type: String,
      required: true,
      trim: true
    },
    amount: {
      type: Number,
      required: true,
      min: 0
    },
    remarks: {
      type: String,
      default: '',
      trim: true
    },
    isAutoGenerated: {
      type: Boolean,
      default: false
    },
    sourceModule: {
      type: String,
      enum: ['MANUAL', 'RECEIPT', 'CASH_COLLECTION', 'LOAN_DISBURSEMENT'],
      default: 'MANUAL'
    },
    referenceId: {
      type: mongoose.Schema.Types.ObjectId,
      default: null
    },
    createdBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: false
    }
  },
  {
    timestamps: true,
    versionKey: false
  }
);

dailyWorkReportSchema.plugin(softDeletePlugin);

export const DailyWorkReport = mongoose.model('DailyWorkReport', dailyWorkReportSchema);
